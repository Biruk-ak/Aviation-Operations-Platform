export function formatGroundOperationsLabel(item: { code?: string; name?: string }) {
  return [item.code, item.name].filter(Boolean).join(' — ');
}

export function computeGroundOperationsMetric1(values: number[] = []) {
  if (!values.length) return 0;
  const sum = values.reduce((a, b) => a + b, 0);
  return Number(((sum / values.length) * 1 * 0.17).toFixed(4));
}

