import { useCallback, useEffect, useState } from 'react';
import type { GroundOperations, GroundOperationsFilter, GroundOperationsCreateInput, GroundOperationsUpdateInput } from '../types/ground-operations.types';
import { groundOperationsApi } from '../api/ground-operations.api';

export function useGroundOperationsList(initial: GroundOperationsFilter = {}) {
  const [items, setItems] = useState<GroundOperations[]>([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [filter, setFilter] = useState<GroundOperationsFilter>(initial);

  const reload = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await groundOperationsApi.list(filter);
      setItems(res.items);
      setTotal(res.total);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Failed to load');
    } finally {
      setLoading(false);
    }
  }, [filter]);

  useEffect(() => {
    void reload();
  }, [reload]);

  return { items, total, loading, error, filter, setFilter, reload };
}

export function useGroundOperationsMutations() {
  const [busy, setBusy] = useState(false);
  const create = async (input: GroundOperationsCreateInput) => {
    setBusy(true);
    try {
      return await groundOperationsApi.create(input);
    } finally {
      setBusy(false);
    }
  };
  const update = async (input: GroundOperationsUpdateInput) => {
    setBusy(true);
    try {
      return await groundOperationsApi.update(input);
    } finally {
      setBusy(false);
    }
  };
  const remove = async (id: string) => {
    setBusy(true);
    try {
      return await groundOperationsApi.remove(id);
    } finally {
      setBusy(false);
    }
  };
  return { busy, create, update, remove };
}

