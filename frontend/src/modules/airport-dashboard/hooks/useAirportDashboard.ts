import { useCallback, useEffect, useState } from 'react';
import type { AirportDashboard, AirportDashboardFilter, AirportDashboardCreateInput, AirportDashboardUpdateInput } from '../types/airport-dashboard.types';
import { airportDashboardApi } from '../api/airport-dashboard.api';

export function useAirportDashboardList(initial: AirportDashboardFilter = {}) {
  const [items, setItems] = useState<AirportDashboard[]>([]);
  const [total, setTotal] = useState(0);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [filter, setFilter] = useState<AirportDashboardFilter>(initial);

  const reload = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await airportDashboardApi.list(filter);
      setItems(res.items);
      setTotal(res.total);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Failed to load');
    } finally {
      setLoading(false);
    }
  }, [filter]);

  useEffect(() => {
    void reload();
  }, [reload]);

  return { items, total, loading, error, filter, setFilter, reload };
}

export function useAirportDashboardMutations() {
  const [busy, setBusy] = useState(false);
  const create = async (input: AirportDashboardCreateInput) => {
    setBusy(true);
    try {
      return await airportDashboardApi.create(input);
    } finally {
      setBusy(false);
    }
  };
  const update = async (input: AirportDashboardUpdateInput) => {
    setBusy(true);
    try {
      return await airportDashboardApi.update(input);
    } finally {
      setBusy(false);
    }
  };
  const remove = async (id: string) => {
    setBusy(true);
    try {
      return await airportDashboardApi.remove(id);
    } finally {
      setBusy(false);
    }
  };
  return { busy, create, update, remove };
}

